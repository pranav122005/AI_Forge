def _make_readme(project_name: str, spec: str, plan: dict[str, Any]) -> str:
    selected = plan.get("selected_components", [])
    exec_status = _execution_status(plan)
    exec_label = {"ready": "✅ Fully executable", "partial": "⚠️ Partial — catalog components require future activation", "blocked": "❌ Blocked — no executable components"}.get(exec_status, exec_status)

    lines = [
        f"# {project_name}",
        "",
        "> Generated by **AIForge** from a natural-language specification.",
        "",
        "## Specification",
        "",
        spec,
        "",
        f"## Execution status: {exec_label}",
        "",
        "## Pipeline components",
        "",
    ]
    for step in plan.get("pipeline_steps", []):
        icon = "✅" if step.get("executable") else "🔵"
        tag = "MVP ready" if step.get("executable") else "Catalog — not yet executable"
        lines.append(f"{step['order']}. {icon} **{step['name']}** — {tag}")
        if step.get("reason"):
            lines.append(f"   - _{step['reason']}_")
    lines += [
        "",
        "## Quick start",
        "",
        "```bash",
        "pip install -r requirements.txt",
        "uvicorn agent.server:app --host 0.0.0.0 --port 8000",
        "```",
        "",
        "## Training (text classifier)",
        "",
        "```bash",
        "# POST a labeled CSV to the AIForge training endpoint",
        "curl -X POST 'http://localhost:8000/api/train?project_id=<project_id>' \\",
        "     -F 'dataset=@your_data.csv'",
        "```",
        "",
        "## Prediction",
        "",
        "```bash",
        'curl -X POST http://localhost:8000/predict \\',
        '     -H "Content-Type: application/json" \\',
        '     -d \'{"text": "Your input text here"}\'',
        "```",
        "",
        "---",
        "",
        "*AIForge MVP — catalog components will be activated in future phases.*",
    ]
    return "\n".join(lines) + "\n"


def _make_requirements(plan: dict[str, Any]) -> str:
    """
    Always include the executable core.  Add notes for catalog components.
    """
    selected = plan.get("selected_components", [])
    has_opencv = "opencv" in selected and REGISTRY.get("opencv", {}).get("executable", False)
    has_ocr = "ocr" in selected and REGISTRY.get("ocr", {}).get("executable", False)

    pkgs = [
        "# Core serving",
        "fastapi>=0.115",
        "uvicorn[standard]>=0.34",
        "python-multipart>=0.0.9",
        "",
    ]
    if "text_classifier" in selected:
        pkgs += [
            "# Text classification (executable)",
            "scikit-learn>=1.5",
            "joblib>=1.4",
            "pandas>=2.2",
            "",
        ]
    if has_opencv:
        pkgs += [
            "# Vision preprocessing (executable)",
            "opencv-python-headless>=4.9",
            "Pillow>=10.0",
            "numpy>=1.24",
            "",
        ]
    if has_ocr:
        pkgs += [
            "# OCR (executable — requires Tesseract system binary)",
            "# Install: https://github.com/UB-Mannheim/tesseract/wiki",
            "pytesseract>=0.3",
            "",
        ]
    catalog_in_plan = [
        c for c in selected
        if not REGISTRY.get(c, {}).get("executable", False) and c not in ("fastapi",)
    ]
    if catalog_in_plan:
        pkgs += [
            "# Catalog components — packages listed for reference only.",
            "# These components are not yet executable in the AIForge MVP.",
            "# Uncomment and install when you activate them.",
        ]
        for cid in catalog_in_plan:
            comp = REGISTRY.get(cid, {})
            name = comp.get("name", cid)
            if comp.get("requires_system_binary"):
                guide = comp.get("install_guide", "see AIForge docs")
                pkgs.append(f"# {name}: requires system binary — {guide}")
            else:
                pkgs.append(f"# {name}: see AIForge docs for activation instructions")
        pkgs.append("")
    pkgs += ["# Testing", "pytest>=8.3", "httpx>=0.27"]
    return "\n".join(pkgs) + "\n"


def _make_dockerfile(plan: dict[str, Any]) -> str:
    selected = plan.get("selected_components", [])
    has_opencv = "opencv" in selected and REGISTRY.get("opencv", {}).get("executable", False)
    has_ocr = "ocr" in selected and REGISTRY.get("ocr", {}).get("executable", False)

    pip_pkgs = ["fastapi", "uvicorn[standard]", "python-multipart"]
    if "text_classifier" in selected:
        pip_pkgs += ["scikit-learn", "joblib", "pandas"]
    if has_opencv:
        pip_pkgs += ["opencv-python-headless", "Pillow", "numpy"]
    if has_ocr:
        pip_pkgs.append("pytesseract")

    pip_line = " ".join(pip_pkgs)

    ocr_note = ""
    if has_ocr:
        ocr_note = (
            "# Install Tesseract OCR system binary\n"
            "RUN apt-get update && apt-get install -y tesseract-ocr && rm -rf /var/lib/apt/lists/*\n"
        )

    return dedent(f"""\
        FROM python:3.12-slim
        WORKDIR /app
        COPY requirements.txt /app/
        {ocr_note}RUN pip install --no-cache-dir {pip_line}
        COPY . /app/
        EXPOSE 8000
        CMD ["uvicorn", "agent.server:app", "--host", "0.0.0.0", "--port", "8000"]
    """)



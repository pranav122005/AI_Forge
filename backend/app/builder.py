def _make_test_pipeline(plan: dict[str, Any]) -> str:
    has_classifier = "text_classifier" in plan.get("selected_components", [])
    if has_classifier:
        return dedent('''\
            """Smoke tests for the generated pipeline."""
            import pytest
            from agent.pipeline import run_pipeline, Pipeline


            def test_pipeline_instantiates():
                p = Pipeline()
                assert len(p.steps) > 0


            def test_run_pipeline_returns_dict():
                result = run_pipeline("test input")
                assert isinstance(result, dict)
                assert "text" in result


            def test_run_pipeline_text_preserved():
                result = run_pipeline("hello world")
                assert result["text"] == "hello world"


            def test_pipeline_without_model_records_status():
                """When model.joblib is absent the classifier records a status rather than crashing."""
                result = run_pipeline("some document text")
                # Either trained (has prediction) or untrained (has status field)
                assert "text_classifier_status" in result or "prediction" in result
        ''')
    else:
        return dedent('''\
            """Smoke tests for the generated pipeline (catalog-only)."""
            from agent.pipeline import run_pipeline, Pipeline


            def test_pipeline_instantiates():
                p = Pipeline()
                assert isinstance(p.steps, list)


            def test_run_pipeline_returns_dict():
                result = run_pipeline("test input")
                assert isinstance(result, dict)
                assert "text" in result


            def test_catalog_components_produce_warnings():
                """Catalog components must not silently pretend to work."""
                result = run_pipeline("test input")
                # Catalog components raise NotImplementedError which is
                # caught and recorded as pipeline_warnings.
                assert "pipeline_warnings" in result
        ''')



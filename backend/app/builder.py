"""
AIForge Builder
===============

Consumes a validated planner result and writes a complete, runnable AI project
to disk.  The Builder is the single source of truth for what gets generated.

Design rules
------------
* NEVER generate working code for catalog-only components — they get honest
  stubs that explain their status and what is needed to activate them.
* Executable components (text_classifier, fastapi) get real, working code.
* The generated project is self-contained: requirements.txt + Dockerfile are
  included so it can be shipped and run immediately once model artifacts exist.
* pipeline.py implements a real Component/Pipeline abstraction (not a stub).
  Each step calls its component's run() method; non-executable components raise
  NotImplementedError with a clear message.
* The generated server.py wires the trained model.joblib when text_classifier
  is in the pipeline; otherwise it returns a structured "not_implemented" response.
"""

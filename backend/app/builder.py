def _slugify(value: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9_-]+", "-", value.strip().lower())
    return value.strip("-") or "aiforge-project"


def _execution_status(plan: dict[str, Any]) -> str:
    """
    "ready"   — every runtime component is executable now
    "partial" — pipeline contains catalog/config-required components
    "blocked" — no executable component at all (edge case)
    """
    selected = plan.get("selected_components", [])
    runtime = [c for c in selected if c != "fastapi"]
    if not runtime:
        return "blocked"
    exec_ids = {cid for cid in runtime if REGISTRY.get(cid, {}).get("executable", False)}
    if not exec_ids:
        return "blocked"
    if len(exec_ids) == len(runtime):
        return "ready"
    return "partial"



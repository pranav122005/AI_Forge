def _make_pipeline_py(plan: dict[str, Any]) -> str:
    """
    Generates a pipeline.py with a real Component base class and one
    concrete subclass per selected component.

    Executable components get real run() logic.
    Catalog components get an honest stub that raises NotImplementedError.
    """
    selected = plan.get("selected_components", [])
    steps = plan.get("pipeline_steps", [])

    # Build per-component class bodies
    class_blocks: list[str] = []
    for step in steps:
        cid = step["id"]
        name = step["name"]
        executable = step.get("executable", False)
        deps = step.get("dependencies", [])
        dep_str = ", ".join(deps) if deps else "none"

        if cid == "opencv":
            class_blocks.append(dedent('''\
                class OpencvComponent(Component):
                    """Executable: OpenCV image preprocessing (grayscale, denoise, binarise)."""

                    name = "opencv"

                    def run(self, context: dict) -> dict:
                        image_bytes = context.get("image_bytes")
                        if image_bytes is None:
                            context["opencv_status"] = "skipped_no_image"
                            return context
                        import cv2
                        import numpy as np
                        arr = np.frombuffer(image_bytes, dtype=np.uint8)
                        bgr = cv2.imdecode(arr, cv2.IMREAD_COLOR)
                        if bgr is None:
                            context["opencv_status"] = "error_decode_failed"
                            return context
                        gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
                        denoised = cv2.GaussianBlur(gray, (3, 3), 0)
                        binary = cv2.adaptiveThreshold(
                            denoised, 255,
                            cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
                            cv2.THRESH_BINARY, 15, 8,
                        )
                        context["preprocessed_image"] = binary
                        context["opencv_status"] = "ok"
                        return context
            '''))
        elif cid == "ocr":
            class_blocks.append(dedent('''\
                class OcrComponent(Component):
                    """OCR: Tesseract text extraction (requires Tesseract system binary)."""

                    name = "ocr"

                    def run(self, context: dict) -> dict:
                        preprocessed = context.get("preprocessed_image")
                        if preprocessed is None:
                            context["ocr_status"] = "skipped_no_image"
                            context["ocr_text"] = ""
                            context.setdefault("text", "")
                            return context
                        try:
                            import pytesseract
                            from PIL import Image
                            pil_img = Image.fromarray(preprocessed)
                            text = pytesseract.image_to_string(pil_img, config="--psm 6")
                            context["ocr_text"] = text.strip()
                            context["text"] = text.strip()
                            context["ocr_status"] = "ok"
                        except Exception as exc:
                            context["ocr_status"] = "error"
                            context["ocr_error"] = str(exc)
                            context["ocr_text"] = ""
                            context.setdefault("text", "")
                        return context
            '''))
        elif cid == "text_classifier":
            class_blocks.append(dedent('''\
                class TextClassifierComponent(Component):
                    """Executable: TF-IDF + Logistic Regression text classifier."""

                    name = "text_classifier"

                    def run(self, context: dict) -> dict:
                        import joblib
                        import pathlib
                        model_path = pathlib.Path(__file__).resolve().parent.parent / "models" / "model.joblib"
                        if not model_path.exists():
                            context["text_classifier_status"] = "model_not_trained"
                            context["text_classifier_error"] = (
                                "model.joblib not found. "
                                "Train via POST /api/train?project_id=<id>"
                            )
                            return context
                        model = joblib.load(model_path)
                        text = str(context.get("text", ""))
                        if not text:
                            context["text_classifier_status"] = "skipped_no_text"
                            return context
                        prediction = model.predict([text])[0]
                        probs = model.predict_proba([text])[0]
                        classes = model.classes_.tolist()
                        ranked = sorted(
                            [{"label": c, "confidence": round(float(p), 4)}
                             for c, p in zip(classes, probs)],
                            key=lambda x: x["confidence"],
                            reverse=True,
                        )[:3]
                        context["prediction"] = str(prediction)
                        context["confidence"] = round(float(max(probs)), 4)
                        context["top_predictions"] = ranked
                        context["text_classifier_status"] = "ok"
                        return context
            '''))
        elif executable:
            # Other executable components (future-proofing)
            class_name = "".join(w.title() for w in cid.split("_")) + "Component"
            class_blocks.append(dedent(f'''\
                class {class_name}(Component):
                    """Executable component: {name}."""

                    name = "{cid}"

                    def run(self, context: dict) -> dict:
                        context["{cid}_status"] = "ok"
                        return context
            '''))
        else:
            # Catalog component — honest stub
            class_name = "".join(w.title() for w in cid.split("_")) + "Component"
            class_blocks.append(dedent(f'''\
                class {class_name}(Component):
                    """Catalog component: {name}.
                    Dependencies: {dep_str}
                    Status: not_implemented — requires external configuration.
                    """

                    name = "{cid}"

                    def run(self, context: dict) -> dict:
                        raise NotImplementedError(
                            "{name} is not yet executable in the AIForge MVP. "
                            "It is included in the generated architecture and "
                            "will be activated in a future phase."
                        )
            '''))

    # Build the ordered pipeline instantiation
    _EXPLICIT_CLASS_NAMES: dict[str, str | None] = {
        "opencv": "OpencvComponent",
        "ocr": "OcrComponent",
        "text_classifier": "TextClassifierComponent",
        "fastapi": None,  # serving layer — not in pipeline.py
    }
    component_class_map: dict[str, str] = {}
    for step in steps:
        cid = step["id"]
        class_name = _EXPLICIT_CLASS_NAMES.get(
            cid, "".join(w.title() for w in cid.split("_")) + "Component"
        )
        if class_name:
            component_class_map[cid] = class_name

    pipeline_steps_code = "[\n"
    for cid, cls in component_class_map.items():
        pipeline_steps_code += f"        {cls}(),\n"
    pipeline_steps_code += "    ]"

    return dedent(f'''\
        """
        Generated AI pipeline — produced by AIForge Builder.

        Architecture: {" → ".join(plan.get("pipeline", []))}

        Execution status: {_execution_status(plan)}
        """
        from __future__ import annotations
        from typing import Any


        class Component:
            """Base class for all pipeline components."""

            name: str = "base"

            def run(self, context: dict) -> dict:
                raise NotImplementedError(f"{{self.__class__.__name__}}.run() not implemented")


        # ---------------------------------------------------------------------------
        # Component implementations
        # ---------------------------------------------------------------------------

    ''') + "\n\n".join(class_blocks) + dedent(f'''

        # ---------------------------------------------------------------------------
        # Pipeline
        # ---------------------------------------------------------------------------

        class Pipeline:
            """
            Executes components in order.
            Catalog components that are not yet executable raise NotImplementedError.
            The pipeline catches those and records them in the context as warnings
            rather than crashing, so partial pipelines still return useful results.
            """

            def __init__(self) -> None:
                self.steps: list[Component] = {pipeline_steps_code}

            def run(self, text: str = "", image_bytes: bytes | None = None) -> dict[str, Any]:
                context: dict[str, Any] = {{
                    "text": text,
                    "image_bytes": image_bytes,
                    "pipeline_warnings": [],
                }}
                for component in self.steps:
                    try:
                        context = component.run(context)
                    except NotImplementedError as exc:
                        context["pipeline_warnings"].append(
                            f"{{component.name}}: {{exc}}"
                        )
                return context


        def run_pipeline(text: str = "", image_bytes: bytes | None = None) -> dict[str, Any]:
            """Convenience wrapper — run the full pipeline."""
            return Pipeline().run(text=text, image_bytes=image_bytes)
    ''')



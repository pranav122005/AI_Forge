def _make_server_py(plan: dict[str, Any]) -> str:
    selected = plan.get("selected_components", [])
    has_classifier = "text_classifier" in selected
    has_opencv = "opencv" in selected and REGISTRY.get("opencv", {}).get("executable", False)
    has_ocr = "ocr" in selected and REGISTRY.get("ocr", {}).get("executable", False)
    has_image_pipeline = has_opencv and has_ocr and has_classifier
    non_exec = [
        REGISTRY[c]["name"]
        for c in selected
        if not REGISTRY.get(c, {}).get("executable", False) and c not in ("fastapi",)
    ]

    if has_classifier:
        image_endpoint = ""
        if has_image_pipeline:
            image_endpoint = dedent('''\

                @app.post("/predict-image")
                async def predict_image(file: UploadFile = File(...)):
                    """
                    Accept an image file, run OpenCV preprocessing + OCR + classifier.
                    Returns the extracted text, prediction and confidence.
                    """
                    import cv2
                    import numpy as np
                    import pytesseract
                    from PIL import Image as PILImage

                    image_bytes = await file.read()

                    # 1. OpenCV preprocessing
                    arr = np.frombuffer(image_bytes, dtype=np.uint8)
                    bgr = cv2.imdecode(arr, cv2.IMREAD_COLOR)
                    if bgr is None:
                        raise HTTPException(status_code=400, detail="Could not decode image")
                    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY)
                    denoised = cv2.GaussianBlur(gray, (3, 3), 0)
                    binary = cv2.adaptiveThreshold(
                        denoised, 255,
                        cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
                        cv2.THRESH_BINARY, 15, 8,
                    )

                    # 2. OCR
                    try:
                        pil_img = PILImage.fromarray(binary)
                        extracted_text = pytesseract.image_to_string(pil_img, config="--psm 6").strip()
                    except Exception as exc:
                        raise HTTPException(
                            status_code=503,
                            detail=f"OCR failed: {exc}. Ensure Tesseract is installed.",
                        )

                    if not extracted_text:
                        return {
                            "extracted_text": "",
                            "prediction": None,
                            "confidence": None,
                            "top_predictions": [],
                            "note": "No text could be extracted from the image",
                        }

                    # 3. Text classification
                    model = _load_model()
                    if model is None:
                        return {
                            "extracted_text": extracted_text,
                            "prediction": None,
                            "confidence": None,
                            "top_predictions": [],
                            "note": "Model not trained yet",
                        }
                    prediction = model.predict([extracted_text])[0]
                    probs = model.predict_proba([extracted_text])[0]
                    classes = model.classes_.tolist()
                    ranked = sorted(
                        [{"label": c, "confidence": round(float(p), 4)} for c, p in zip(classes, probs)],
                        key=lambda x: x["confidence"],
                        reverse=True,
                    )[:3]
                    return {
                        "extracted_text": extracted_text,
                        "prediction": str(prediction),
                        "confidence": round(float(max(probs)), 4),
                        "top_predictions": ranked,
                    }
            ''')

        file_import = "from fastapi import FastAPI, File, HTTPException, UploadFile" if has_image_pipeline else "from fastapi import FastAPI, HTTPException"
        return dedent(f'''\
            """
            Generated FastAPI service — produced by AIForge Builder.
            Loads model.joblib when available and exposes a real /predict endpoint.
            {f"Also exposes /predict-image for the image → OCR → classifier pipeline." if has_image_pipeline else ""}
            """
            from __future__ import annotations
            import pathlib
            {file_import}
            import joblib

            app = FastAPI(title="Generated AI Service")

            _MODEL_PATH = pathlib.Path(__file__).resolve().parent.parent / "models" / "model.joblib"


            def _load_model():
                if not _MODEL_PATH.exists():
                    return None
                return joblib.load(_MODEL_PATH)


            @app.get("/health")
            def health():
                return {{"status": "ok", "model_ready": _MODEL_PATH.exists()}}


            @app.post("/predict")
            def predict(payload: dict):
                text = str(payload.get("text", ""))
                if not text:
                    raise HTTPException(status_code=400, detail="\'text\' field is required")
                model = _load_model()
                if model is None:
                    raise HTTPException(
                        status_code=503,
                        detail=(
                            "Model not trained yet. "
                            "POST a labeled CSV to /api/train?project_id=<id> first."
                        ),
                    )
                prediction = model.predict([text])[0]
                probs = model.predict_proba([text])[0]
                classes = model.classes_.tolist()
                ranked = sorted(
                    [{{"label": c, "confidence": round(float(p), 4)}} for c, p in zip(classes, probs)],
                    key=lambda x: x["confidence"],
                    reverse=True,
                )[:3]
                return {{
                    "prediction": str(prediction),
                    "confidence": round(float(max(probs)), 4),
                    "top_predictions": ranked,
                }}
        ''') + image_endpoint
    else:
        non_exec_str = ", ".join(non_exec) if non_exec else "unknown"
        return dedent(f'''\
            """
            Generated FastAPI service stub — produced by AIForge Builder.

            NOTE: This pipeline includes components that are not yet executable:
            {non_exec_str}

            The /predict endpoint returns an honest "not_implemented" response.
            Activate the catalog components to enable real inference.
            """
            from fastapi import FastAPI

            app = FastAPI(title="Generated AI Service (catalog pipeline)")


            @app.get("/health")
            def health():
                return {{
                    "status": "ok",
                    "model_ready": False,
                    "execution_status": "partial",
                    "catalog_components": {json.dumps(non_exec)},
                }}


            @app.post("/predict")
            def predict(payload: dict):
                return {{
                    "status": "not_implemented",
                    "catalog_components": {json.dumps(non_exec)},
                    "message": (
                        "This pipeline includes components not yet executable in the "
                        "AIForge MVP: {non_exec_str}. "
                        "The architecture has been generated; activate catalog "
                        "components to enable real inference."
                    ),
                }}
        ''')



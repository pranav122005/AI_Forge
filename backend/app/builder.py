class BuildResult:
    """Returned by build_project(); carries all information about the build."""

    def __init__(
        self,
        project_id: str,
        project_name: str,
        project_dir: Path,
        plan: dict[str, Any],
        generated_files: list[str],
    ) -> None:
        self.project_id = project_id
        self.project_name = project_name
        self.project_dir = project_dir
        self.plan = plan
        self.generated_files = generated_files
        self.execution_status = _execution_status(plan)

    def to_dict(self) -> dict[str, Any]:
        return {
            "project_id": self.project_id,
            "project_name": self.project_name,
            "project_path": str(self.project_dir),
            "execution_status": self.execution_status,
            "execution_ready": self.plan.get("execution_ready", False),
            "pipeline": self.plan.get("pipeline", []),
            "pipeline_steps": self.plan.get("pipeline_steps", []),
            "selected_components": self.plan.get("selected_components", []),
            "implemented_components": self.plan.get("implemented_components", []),
            "catalog_components": self.plan.get("catalog_components", []),
            "warnings": self.plan.get("warnings", []),
            "generated_files": self.generated_files,
        }


def build_project(project_name: str, spec: str) -> BuildResult:
    """
    Main entry point.

    1. Calls analyze_spec() to get the structured plan.
    2. Validates the plan.
    3. Writes the full project to disk under GENERATED_DIR.
    4. Returns a BuildResult.
    """
    plan = analyze_spec(spec)

    # Validate all component IDs exist in registry
    for cid in plan.get("selected_components", []):
        if cid not in REGISTRY:
            raise ValueError(f"Unknown component id '{cid}' returned by planner")

    project_id = _slugify(project_name) + "-" + uuid.uuid4().hex[:6]
    project_dir = GENERATED_DIR / project_id
    project_dir.mkdir(parents=True, exist_ok=True)

    # Create subdirectories
    (project_dir / "agent").mkdir(exist_ok=True)
    (project_dir / "models").mkdir(exist_ok=True)
    (project_dir / "tests").mkdir(exist_ok=True)

    # Generate all files
    files: dict[str, str] = {
        "README.md": _make_readme(project_name, spec, plan),
        "requirements.txt": _make_requirements(plan),
        "Dockerfile": _make_dockerfile(plan),
        "pipeline.json": _make_pipeline_json(project_id, project_name, spec, plan),
        "agent/__init__.py": '"""Generated Agent Package."""\n',
        "agent/pipeline.py": _make_pipeline_py(plan),
        "agent/runtime.py": (
            '"""Generated Agent Runtime."""\n\n'
            'from agent.pipeline import run_pipeline\n\n\n'
            'class AgentRuntime:\n'
            '    def run(self, text: str = "", image_bytes: bytes | None = None):\n'
            '        return run_pipeline(text=text, image_bytes=image_bytes)\n'
        ),
        "agent/server.py": _make_server_py(plan),
        "tests/test_pipeline.py": _make_test_pipeline(plan),
    }

    for rel, content in files.items():
        path = project_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    # project.json last (needs generated_files list)
    generated_files = list(files.keys()) + ["project.json"]
    project_json = _make_project_json(project_id, project_name, spec, plan, generated_files)
    (project_dir / "project.json").write_text(project_json, encoding="utf-8")

    return BuildResult(
        project_id=project_id,
        project_name=project_name,
        project_dir=project_dir,
        plan=plan,
        generated_files=generated_files,
    )
